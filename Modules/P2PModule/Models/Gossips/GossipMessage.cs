namespace P2PModule.Models.Gossips;
using System;
using System.Security.Cryptography;

using global::P2PModule.Infrastructure;

/// <summary>
/// Represents a validated gossip broadcast envelope transmitted across the P2P network.
/// Integrates loop mitigation, strict liveness timestamping, priority queue properties, and
/// cryptographic origin validation.
/// </summary>
public class GossipMessage
{
    /// <summary>
    /// Unique identifier of this specific gossip broadcast packet.
    /// Used for flood protection and loop prevention. If a node has already seen this ID, 
    /// it is dropped instantly without further processing or propagation.
    /// </summary>
    public string GossipId { get; set; } = Guid.NewGuid().ToString();

    /// <summary>
    /// The topic channel this gossip broadcast is published to (e.g., "handshake-fault", "consensus-update").
    /// Allows the gossip system to partition handlers similar to the topic-subscription model.
    /// </summary>
    public string Topic { get; set; } = string.Empty;

    /// <summary>
    /// The raw serialized JSON payload containing the actual data or dispute session details.
    /// </summary>
    public string SerializedPayload { get; set; } = string.Empty;

    /// <summary>
    /// Unix millisecond timestamp representing when the origin node instantiated this gossip report.
    /// Used by the DoubleBlindChallengeService to perform liveness evaluations and drop stale messages.
    /// </summary>
    public long CreatedUtcMs { get; set; } = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();

    /// <summary>
    /// Priority level of the gossip packet. Lower values represent higher priority 
    /// (e.g., 1 for handshake failure reports, 10 for background node list synchronizations).
    /// Used to order the single PriorityQueue inside the GossipService.
    /// </summary>
    public int Priority { get; set; } = 5;

    /// <summary>
    /// The NodeId of the peer that originally generated and signed this gossip report.
    /// </summary>
    public string OriginNodeId { get; set; } = string.Empty;

    /// <summary>
    /// Cryptographic signatures generated by the origin node's certificate from
    /// hash of content string representing this gossip packet's core contents 
    /// (GossipId + Topic + CreatedUtcMs + SerializedPayload + OriginNodeId).
    /// </summary>
    public byte[] Signature { get; set; } = new byte[0];

    public byte[] GetNodeDataHash()
    {
        var payloadHash = Convert.ToBase64String(SHA256.HashData(Convert.FromBase64String(P2PCrypto.CrCompliantStr(SerializedPayload))));

        return SHA256.HashData(
            Convert.FromBase64String(P2PCrypto.CrCompliantStr(
                $"{GossipId}|{Topic}|{CreatedUtcMs}|{OriginNodeId}|{payloadHash}")));
    }
}

/// <summary>
/// Since we do not trust ANYONE we need someone we can trust
/// We can trust a node gossiping its own node data
/// We can trust new gossiped node data IF we already posess the verification key
/// for that node and nodedata is signed by it
/// </summary>
public class NodeUpdateData
{
    public PeerImmutableData Identity { get; set; } = new();
    //daykey - signature
    public List<SignatureEnvelope> Signatures { get; set; } = new();
}

public class ChainSignature
{
    public int Order { get; set; }
    public string NodeId { get; set; }
    public byte[] Signature { get; set; }
}

public class NodeUpdateGossip
{
    public List<NodeUpdateData> Nodes { get; set; } = new();
}